"""Generate figs/colourgrid.tex, a packed mosaic of coloured polyominoes.

Every cell belongs to a piece. A thin snake has the most cells, a compact blob is the most stable,
one cluster of touching pieces shares a colour, and single cells are rare.
Run: python3 -I make_colourgrid.py  (writes colourgrid.tex next to this file)
"""
import random
from pathlib import Path

N, SEED = 16, 3
COLOURS = ["blue!70", "orange!80", "green!60!black", "violet!70", "red!70", "teal!70", "yellow!80!black", "cyan!60", "magenta!60"]
rng = random.Random(SEED)
piece = [[None] * N for _ in range(N)]
NB = ((1, 0), (-1, 0), (0, 1), (0, -1))


def place(pid, cells):
    for x, y in cells:
        piece[x][y] = pid


# fixed pieces, cells as (x, y) with y up
blob = [(x, y) for x in range(10, 15) for y in range(10, 15) if (x, y) != (14, 14)]
snake = [(x, 1) for x in range(1, 12)] + [(11, y) for y in range(2, 7)] + [(x, 6) for x in range(12, 16)]
place(0, blob)
place(1, snake)


def grow(pid, start, size):
    cells, frontier = [start], [start]
    piece[start[0]][start[1]] = pid
    while len(cells) < size and frontier:
        x, y = rng.choice(frontier)
        free = [(x + dx, y + dy) for dx, dy in NB
                if 0 <= x + dx < N and 0 <= y + dy < N and piece[x + dx][y + dy] is None]
        if not free:
            frontier.remove((x, y))
            continue
        c = rng.choice(free)
        piece[c[0]][c[1]] = pid
        cells.append(c)
        frontier.append(c)
    return cells


pid = 2
sizes = {}
free_cells = [(x, y) for x in range(N) for y in range(N) if piece[x][y] is None]
rng.shuffle(free_cells)
for c in free_cells:
    if piece[c[0]][c[1]] is None:
        size = rng.choice([3, 4, 4, 5, 5, 6, 6, 7, 8, 9, 11, 13])
        sizes[pid] = len(grow(pid, c, size))
        pid += 1

# fold most single cells into a neighbour, keeping a couple
singles = [p for p, s in sizes.items() if s == 1]
for p in singles[2:]:
    (x, y), = [(x, y) for x in range(N) for y in range(N) if piece[x][y] == p]
    nbrs = [piece[x + dx][y + dy] for dx, dy in NB if 0 <= x + dx < N and 0 <= y + dy < N]
    piece[x][y] = rng.choice([q for q in nbrs if q > 1] or nbrs)

# adjacency between pieces
ids = sorted({piece[x][y] for x in range(N) for y in range(N)})
adj = {p: set() for p in ids}
for x in range(N):
    for y in range(N):
        for dx, dy in ((1, 0), (0, 1)):
            if x + dx < N and y + dy < N and piece[x][y] != piece[x + dx][y + dy]:
                adj[piece[x][y]].add(piece[x + dx][y + dy])
                adj[piece[x + dx][y + dy]].add(piece[x][y])

# one same-colour cluster: a small piece away from the fixed ones and two of its small neighbours
size = {p: sum(row.count(p) for row in piece) for p in ids}
small = lambda p: p > 1 and size[p] <= 5
cand = [p for p in ids if small(p) and not adj[p] & {0, 1} and sum(map(small, adj[p])) >= 2]
seed_p = rng.choice(cand)
cluster = {seed_p, *sorted(q for q in adj[seed_p] if small(q))[:2]}

# greedy colouring, cluster as one node, fixed colours for blob and snake
colour = {0: 0, 1: 1}
for p in cluster:
    colour[p] = 3
order = [p for p in ids if p not in colour]
rng.shuffle(order)
for p in order:
    used = {0, 1} | {colour[q] for q in adj[p] if q in colour}  # blob and snake colours are unique
    if p in adj[seed_p] or any(p in adj[q] for q in cluster):
        used.add(3)
    colour[p] = next(c for c in rng.sample(range(len(COLOURS)), len(COLOURS)) if c not in used)

out = ["% Generated by make_colourgrid.py, do not edit by hand.",
       "% Packed mosaic of coloured polyominoes; the orange snake has the most cells, the blue blob is the most stable,",
       "% the violet cluster is touching pieces that share a colour and so form one outcome region.",
       r"\begin{tikzpicture}[x=0.25cm, y=0.25cm]"]
for x in range(N):
    for y in range(N):
        out.append(rf"  \fill[{COLOURS[colour[piece[x][y]]]}] ({x},{y}) rectangle ++(1,1);")
out.append(r"  \draw[white, ultra thin, opacity=0.6, xstep=0.25cm, ystep=0.25cm] (0,0) grid (16,16);")
# piece borders
for x in range(N):
    for y in range(N):
        if x + 1 < N and piece[x][y] != piece[x + 1][y]:
            out.append(rf"  \draw[black!70, semithick] ({x + 1},{y}) -- ++(0,1);")
        if y + 1 < N and piece[x][y] != piece[x][y + 1]:
            out.append(rf"  \draw[black!70, semithick] ({x},{y + 1}) -- ++(1,0);")
out += [r"  \draw[thick] (0,0) rectangle (16,16);",
        r"  \fill[black] (4.5,3.5) circle (0.5);",
        r"  \fill[white] (4.5,3.5) circle (0.25);",
        r"  \draw[-{Stealth[length=1.5mm]}, very thick, white] (4.5,3.5) to[bend right=25] (12,12);",
        r"  \draw[-{Stealth[length=1.5mm]}, thick, black, dashed] (4.5,3.5) to[bend right=25] (12,12);",
        r"  \node[below, font=\scriptsize] at (8,0) {$n \times n$ grid, $Z$ the colour of the current cell};",
        r"\end{tikzpicture}", ""]
Path(__file__).with_name("colourgrid.tex").write_text("\n".join(out))
final = {}
for x in range(N):
    for y in range(N):
        final[piece[x][y]] = final.get(piece[x][y], 0) + 1
print("pieces", len(final), "singles", sum(s == 1 for s in final.values()), "cluster", sorted(final[p] for p in cluster))
